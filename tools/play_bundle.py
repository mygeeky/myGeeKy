"""Build the Google Play bundle (.aab) here, signed with the upload key, into google-play/.

    python tools/play_bundle.py

The upload key lives outside the repo, in ~/.config/mygeeky-play/upload-keystore.jks (alias `upload`), and its
password in the system keyring (service `mygeeky-play-upload-key`, user `upload`): never in a file, a log or the
command line shown here. Google re-signs the app for the store (Play App Signing), so a lost upload key can be reset
through Play support -- but keep a backup of the keystore and the password anyway.

The version code comes from mobile/app.json (android.versionCode, kept as major*10000 + minor*100 + patch of
expo.version) and must rise with every upload. mobile/android/ is generated by `expo prebuild` and never edited:
Gradle builds the bundle with its debug key, and this script re-signs it with the upload key (jarsigner).
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOBILE = ROOT / "mobile"
KEYSTORE = Path.home() / ".config" / "mygeeky-play" / "upload-keystore.jks"
SERVICE, USER = "mygeeky-play-upload-key", "upload"


def main() -> None:
    import keyring
    password = keyring.get_password(SERVICE, USER)
    if not password or not KEYSTORE.exists():
        sys.exit(f"No upload key: {KEYSTORE} and its password in the keyring ({SERVICE}) are both needed.")
    expo = json.loads((MOBILE / "app.json").read_text(encoding="utf-8"))["expo"]
    version, code = expo["version"], expo["android"].get("versionCode")
    major, minor, patch = (int(x) for x in version.split("."))
    if code != major * 10000 + minor * 100 + patch:
        sys.exit(f"mobile/app.json: android.versionCode is {code}, expected {major * 10000 + minor * 100 + patch} "
                 f"for version {version}.")
    env = {**os.environ, "ANDROID_HOME": os.environ.get("ANDROID_HOME", str(Path.home() / "Android" / "Sdk"))}
    saved = Path(tempfile.mkdtemp()) / "package.json"
    shutil.copyfile(MOBILE / "package.json", saved)          # prebuild rewrites its scripts
    try:
        subprocess.run(["npx", "expo", "prebuild", "-p", "android", "--clean", "--no-install"], cwd=MOBILE, env=env,
                       check=True)
    finally:
        shutil.copyfile(saved, MOBILE / "package.json")
    subprocess.run(["./gradlew", "bundleRelease", "--no-daemon", "-q"], cwd=MOBILE / "android", env=env, check=True)
    built = MOBILE / "android" / "app" / "build" / "outputs" / "bundle" / "release" / "app-release.aab"
    out = ROOT / "google-play" / f"myGeeKy-{version}-{code}.aab"
    # Gradle signs it with the debug key: drop that signature, then sign with the upload key. jarsigner reads the
    # password from its environment (-storepass:env), so it never appears on a command line.
    with zipfile.ZipFile(built) as src, zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for item in src.infolist():
            name = item.filename.upper()
            if name.startswith("META-INF/") and (name.endswith((".SF", ".RSA", ".DSA", ".EC")) or
                                                 name == "META-INF/MANIFEST.MF"):
                continue
            dst.writestr(item, src.read(item.filename))
    subprocess.run(["jarsigner", "-sigalg", "SHA256withRSA", "-digestalg", "SHA-256", "-keystore", str(KEYSTORE),
                    "-storepass:env", "UPLOAD_KEY_PASSWORD", "-keypass:env", "UPLOAD_KEY_PASSWORD", str(out), USER],
                   env={**env, "UPLOAD_KEY_PASSWORD": password}, check=True, capture_output=True)
    with zipfile.ZipFile(out) as z:                # nothing play_check.py refuses or calls unneeded slipped back in
        manifest = z.read("base/manifest/AndroidManifest.xml")
    sys.path.insert(0, str(ROOT / "tools"))
    from play_check import FORBIDDEN, UNNEEDED
    found = [p for p in (*FORBIDDEN, *UNNEEDED) if p.encode() in manifest or p.encode("utf-16-le") in manifest]
    if found:
        sys.exit(f"{out.name} still asks for {', '.join(found)}: block them in mobile/app.json (blockedPermissions).")
    check = subprocess.run(["jarsigner", "-verify", "-verbose", "-certs", str(out)], capture_output=True, text=True)
    owner = next((line.strip() for line in check.stdout.splitlines() if "CN=" in line), "")
    if "jar verified" not in check.stdout or "myGeeKy" not in owner:
        sys.exit(f"{out.name} isn't signed with the upload key:\n{check.stdout[-800:]}")
    print(f"{out.relative_to(ROOT)} ({out.stat().st_size / 1e6:.0f} MB), version {version} ({code}), {owner}")


if __name__ == "__main__":
    main()
